/// Espaçamentos padrão do FinTrack.
/// Usar em paddings, margins e gaps em vez de valores aleatórios.
class AppSpacing {
  AppSpacing._();

  /// 4px — entre ícone e texto, gaps muito pequenos
  static const double xs = 4;

  /// 8px — entre itens de uma lista
  static const double sm = 8;

  /// 12px — entre elementos relacionados
  static const double md = 12;

  /// 16px — padding interno de cards, entre seções próximas
  static const double lg = 16;

  /// 24px — entre seções grandes, padding lateral da tela
  static const double xl = 24;

  /// 32px — separação entre blocos principais
  static const double xxl = 32;

  /// 48px — altura mínima de botões e inputs (padrão Material)
  static const double touchTarget = 48;
}